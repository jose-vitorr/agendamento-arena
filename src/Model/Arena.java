public abstract class Arena {
    private String nome;
    private String endereco;
    private String num_whatsapp;
    private float percentual_sinal_padrao;
    

    public Arena(){
        this.nome= nome;
        this.endereco= endereco;
        this.num_whatsapp= num_whatsapp;
        this.percentual_sinal_padrao= percentual_sinal_padrao;
        
    }


}
